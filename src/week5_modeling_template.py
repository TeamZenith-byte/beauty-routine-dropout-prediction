    # ---- PHASE 1: training data only (tuning, out-of-fold threshold, label-shuffle check, importance)
    for name, (pipe, grid) in make_models(numeric, categorical, a.seed, a.resample).items():
        gs = tune(name, pipe, grid, X_tr, y_tr, splits)               # FINAL model: tuned on all training rows
        best = gs.best_estimator_
        # Threshold from NESTED out-of-fold predictions (tuning never saw the rows it predicts).
        oof, _, fold_params = nested_oof(pipe, grid, X_tr, y_tr, g_tr, a.outer_folds, a.inner_folds, a.seed)
        thr = choose_threshold(y_tr.values, oof, 2.0, a.cost_fn, a.cost_fp)
        nested_pr = float(average_precision_score(y_tr, oof))
        same = sum(fp == gs.best_params_ for fp in fold_params)
        entry = {"best_params": gs.best_params_, "threshold_from_nested_oof": round(thr, 4),
                 "nested_cv_pr_auc": nested_pr, "nested_cv_roc_auc": float(roc_auc_score(y_tr, oof)),
                 "tuning_cv_pr_auc_optimistic": float(gs.best_score_),
                 "outer_fold_best_params": fold_params,
                 "share_outer_folds_choosing_final_params": same / len(fold_params)}
        entry["label_shuffle_check"] = label_shuffle_check(pipe, grid, X_tr, y_tr, g_tr, nested_pr, a.outer_folds,
                                                          a.inner_folds, a.shuffle_repeats, a.seed)
        tables[name] = interpret(name, best, X_tr, y_tr, splits, a.seed)
        if name == "decision_tree":
            (outdir / f"{pre}decision_tree_rules.txt").write_text(
                export_text(best.named_steps["model"], feature_names=list(best.named_steps["prep"].get_feature_names_out())))
        frozen[name] = (best, thr); summary[name] = entry

    # ---- PHASE 2: everything is frozen. Each model meets the test set exactly once.
    results = {}
    for name, (best, thr) in frozen.items():
        metrics, proba = locked.evaluate_once(name, best, thr)
        summary[name]["test"] = metrics
        results[name] = {"y_te": y_te.values, "proba": proba, "metrics": metrics}
        print(f"{name:20s} best={summary[name]['best_params']}  threshold={thr:.3f}  recall={metrics['recall']:.2f}  "
              f"precision={metrics['precision']:.2f}  PR-AUC={metrics['pr_auc_average_precision']:.3f}")
    dummy = DummyClassifier(strategy="prior").fit(X_tr, y_tr)
    summary["dummy_prior_baseline"] = {"pr_auc_average_precision": average_precision_score(y_te, dummy.predict_proba(X_te)[:, 1]),
                                       "note": "equals the dropout prevalence; every model must beat it"}
    locked.uses["dummy_prior_baseline"] = 1

    # ---- PHASE 3: reporting only (nothing below feeds back into any choice)
    src = "SIMULATED" if simulated else "REAL"
    for nm, t in tables.items():
        eff = (t[0] if isinstance(t, tuple) else t).copy(); eff.insert(0, "data_source", src)
        eff.to_csv(outdir / f"{pre}{nm}_feature_effects.csv", index=False)
        if isinstance(t, tuple):
            pi = t[1].rename("pr_auc_drop_on_training_validation_folds").to_frame(); pi.insert(0, "data_source", src)
            pi.to_csv(outdir / f"{pre}{nm}_permutation_importance.csv")
    plot_results(results, outdir, "SIMULATED DEMO - NOT REAL RESULTS" if simulated else None, pre)
    manifest = {"created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                "data_source": "SIMULATED" if simulated else a.data, "data_sha256": data_hash,
                "seed": a.seed, "n_rows": len(df), "dropout_rate": float(y.mean()),
                "features_numeric": numeric, "features_categorical": categorical,
                "group_col": group_col, "group_aware_everywhere": bool(group_col), "resample": a.resample,
                "threshold_method": "nested out-of-fold (outer folds tune on outer-training rows only)",
                "outer_folds": a.outer_folds, "inner_folds": a.inner_folds, "script_version": "week5-v3",
                "test_set_use": {"scored_once_per_model": locked.uses, "used_for_selection_or_tuning": False,
                                 "permutation_importance_data": "training-set validation folds"},
                "versions": {"python": platform.python_version(), "scikit_learn": sklearn.__version__,
                             "pandas": pd.__version__, "numpy": np.__version__},
                "warning": SIM_BANNER if simulated else "Real-data run: report only after leakage review.",
                "models": summary}
    (outdir / f"{pre}run_manifest.json").write_text(json.dumps(manifest, indent=2, default=float))
    print("outputs written to", outdir)
    return 0 if strict_ok else 1


