# --8<-- A_leakage_guard
def guard_leakage(features, target, id_col=None, group_col=None):
    """Refuse feature names that look like the outcome or were measured after it."""
    bad = [c for c in features
           if c in (target, id_col, group_col) or any(w in c.lower() for w in LEAK_WORDS)]
    if bad:
        raise ValueError(f"Possible leakage or identifier columns among features: {bad}")
# --8<-- end


def make_simulated_data(n=600, seed=SEED, grouped=False):
    """SIMULATED survey-like table. The target rule below is INVENTED to exercise the code.
    grouped=True gives several rows per participant (same participant-level label) to test group-aware splits."""
    rng = np.random.default_rng(seed)
    if grouped:
        n_part = max(n // 3, 30)
        part = rng.integers(0, n_part, n)
        part_effect = rng.normal(0, 0.8, n_part)[part]
        pid = np.array([f"P{i:04d}" for i in part])
    else:
        part_effect, pid = 0.0, np.array([f"P{i:04d}" for i in range(n)])
    steps = np.clip(rng.poisson(5.5, n), 1, 14)
    minutes = np.clip(rng.normal(8 + 2.2 * steps, 6, n), 3, 90)
    cost = np.round(rng.lognormal(3.4 + 0.04 * steps, 0.5, n), 1)          # invented cost per use
    freq = rng.integers(1, 8, n)
    afford = np.clip(np.round(rng.normal(3.2, 1.0, n)), 1, 5)
    irritation = rng.poisson(0.6, n)
    satisf = np.clip(np.round(rng.normal(3.6, 1.0, n) - 0.4 * irritation), 1, 5)
    concern = rng.choice(["acne", "dryness", "pigmentation", "anti_ageing", "none_stated"], n)
    z = (-3.2 + 0.22 * steps + 0.03 * minutes + 0.012 * cost - 0.18 * freq
         - 0.35 * (afford - 3) + 0.5 * irritation - 0.3 * (satisf - 3) + part_effect)
    y = (rng.random(n) < 1 / (1 + np.exp(-z))).astype(int)
    df = pd.DataFrame({"person_id": [f"R{i:04d}" for i in range(n)], "participant_id": pid,
                       "routine_step_count": steps, "time_burden_min_day": minutes,
                       "cost_per_use": cost, "usage_frequency_per_week": freq,
                       "perceived_affordability": afford, "irritation_event_count": irritation,
                       "routine_satisfaction": satisf, "skin_concern_category": concern, TARGET: y})
    if grouped:                                       # outcome belongs to the participant, not the row
        df[TARGET] = df.groupby("participant_id")[TARGET].transform("max")
    for col, share in [("time_burden_min_day", 0.08), ("cost_per_use", 0.10), ("perceived_affordability", 0.05)]:
        df.loc[rng.random(n) < share, col] = np.nan            # missing values on purpose
    df.loc[rng.random(n) < 0.04, "skin_concern_category"] = np.nan
    return df


def read_dictionary(path, df):
    d = pd.read_csv(path)
    need = {"name", "role", "type", "measured_at"}
    if not need.issubset(d.columns):
        raise ValueError(f"Dictionary needs columns {sorted(need)}")
    feats = d[d.role == "feature"]
    late = feats[feats.measured_at != "baseline"].name.tolist()
    if late:
        raise ValueError(f"Features not measured at baseline (leakage risk): {late}")
    missing = [c for c in d.name if c not in df.columns]
    if missing:
        raise ValueError(f"Dictionary columns not in data: {missing}")
    get = lambda r: d[d.role == r].name.tolist()
    return (feats[feats.type == "numeric"].name.tolist(), feats[feats.type == "categorical"].name.tolist(),
            (get("id") or [None])[0], (get("group") or [None])[0])


# --8<-- B_split
def stratified_holdout(X, y, groups=None, test_size=0.2, seed=SEED):
    """Stratified hold-out; group-aware when one person/household has several rows."""
    if groups is None:
        return train_test_split(X, y, test_size=test_size, stratify=y, random_state=seed)
    sgk = StratifiedGroupKFold(n_splits=int(round(1 / test_size)), shuffle=True, random_state=seed)
    tr, te = next(sgk.split(X, y, groups))
    return X.iloc[tr], X.iloc[te], y.iloc[tr], y.iloc[te]
# --8<-- end


# --8<-- C_preprocessing
def make_preprocessor(numeric, categorical, scale):
    """scale=True for Logistic Regression; trees and forests do not need scaling."""
    num = [("impute", SimpleImputer(strategy="median", add_indicator=True))]
    if scale:
        num.append(("scale", StandardScaler()))
    cat = [("impute", SimpleImputer(strategy="constant", fill_value="unknown")),
           ("onehot", OneHotEncoder(handle_unknown="ignore"))]
    return ColumnTransformer([("num", Pipeline(num), numeric), ("cat", Pipeline(cat), categorical)])
# --8<-- end


# --8<-- D_models
def make_models(numeric, categorical, seed=SEED, resample=None):
    def pipe(prep, model):
        if resample == "smote":                      # optional; needs imbalanced-learn
            from imblearn.pipeline import Pipeline as ImbPipeline
            from imblearn.over_sampling import SMOTE
            return ImbPipeline([("prep", prep), ("smote", SMOTE(random_state=seed)), ("model", model)])
        return Pipeline([("prep", prep), ("model", model)])
    cw = None if resample == "smote" else "balanced"
    return {
        "logistic_regression": (
            pipe(make_preprocessor(numeric, categorical, True),
                 LogisticRegression(class_weight=cw, max_iter=2000, random_state=seed)),
            {"model__C": [0.01, 0.1, 1, 10, 100]}),
        "decision_tree": (
            pipe(make_preprocessor(numeric, categorical, False),
                 DecisionTreeClassifier(class_weight=cw, random_state=seed)),
            {"model__max_depth": [2, 3, 4, 5, 6], "model__min_samples_leaf": [5, 10, 20, 40],
             "model__ccp_alpha": [0.0, 0.002, 0.01], "model__criterion": ["gini", "entropy"]}),
        "random_forest": (
            pipe(make_preprocessor(numeric, categorical, False),
                 RandomForestClassifier(n_estimators=200, class_weight=None if resample else "balanced_subsample",
                                        n_jobs=1, random_state=seed)),
            {"model__max_depth": [None, 4, 8], "model__min_samples_leaf": [1, 5, 10],
             "model__max_features": ["sqrt", 0.5]}),
    }
# --8<-- end


# --8<-- E_tuning
def make_splits(X, y, groups=None, folds=5, seed=SEED):
    """ONE list of (train, validation) index pairs, reused for tuning, out-of-fold
    threshold selection, the label-shuffle check and permutation importance."""
    if groups is None:
        return list(StratifiedKFold(folds, shuffle=True, random_state=seed).split(X, y))
    splits = list(StratifiedGroupKFold(folds, shuffle=True, random_state=seed).split(X, y, groups))
    g = np.asarray(groups)
    for tr, va in splits:                              # participant-level leakage guard
        if set(g[tr]) & set(g[va]):
            raise RuntimeError("A participant appears in both training and validation rows of one fold")
    return splits


def tune(name, pipeline, grid, X_tr, y_tr, splits):
    """Hyper-parameters are chosen on the training data only, scored by PR-AUC."""
    gs = GridSearchCV(pipeline, grid, cv=splits, scoring="average_precision", refit=True, n_jobs=-1)
    return gs.fit(X_tr, y_tr)


def nested_oof(pipeline, grid, X, y, groups=None, outer=5, inner=3, seed=SEED):
    """NESTED out-of-fold probabilities (training data only; group-aware when groups are given).
    For each OUTER fold: tune hyper-parameters with INNER folds using only the outer-training
    rows, then predict the outer-validation rows, which that tuning never saw. Every training
    row therefore gets exactly one probability from a model whose settings were chosen without
    it. Use these probabilities (not the tuned model's own cross_val_predict) to pick the
    threshold and to estimate training-side PR-AUC."""
    outer_splits = make_splits(X, y, groups, outer, seed + 101)
    oof, fold_params = np.full(len(y), np.nan), []
    for tr, va in outer_splits:
        Xtr, ytr = X.iloc[tr], y.iloc[tr]
        gtr = groups.iloc[tr] if groups is not None else None
        inner_splits = make_splits(Xtr, ytr, gtr, inner, seed + 202)     # fresh folds inside the outer-training rows
        gs = tune(None, pipeline, grid, Xtr, ytr, inner_splits)
        oof[va] = gs.predict_proba(X.iloc[va])[:, 1]
        fold_params.append(gs.best_params_)
    if np.isnan(oof).any():
        raise RuntimeError("Nested folds did not cover every training row")
    return oof, outer_splits, fold_params
# --8<-- end


# --8<-- F_evaluation
def choose_threshold(y_true, proba, beta=2.0, cost_fn=None, cost_fp=None):
    """Pick a threshold from NESTED out-of-fold training probabilities (never from the test set).
    Default: maximise F-beta (beta=2 favours recall). If costs are given: minimise cost."""
    prec, rec, thr = precision_recall_curve(y_true, proba)
    ok = prec[:-1] > float(np.mean(y_true)) + 0.02      # must beat "flag everybody" (precision = prevalence)
    if not ok.any():
        return 0.5                                       # model has no useful signal; fall back and say so
    prec, rec, thr = prec[:-1][ok], rec[:-1][ok], thr[ok]
    if cost_fn is not None and cost_fp is not None:
        costs = [cost_fn * np.sum((proba < t) & (y_true == 1)) + cost_fp * np.sum((proba >= t) & (y_true == 0))
                 for t in thr]
        return float(thr[int(np.argmin(costs))])
    fb = (1 + beta**2) * prec * rec / np.clip(beta**2 * prec + rec, 1e-12, None)
    return float(thr[int(np.argmax(fb))])


class LockedTestSet:
    """Holds the test rows. Each model may be scored on them exactly once, after its
    hyper-parameters and threshold are frozen. A second use raises an error."""
    def __init__(self, X, y):
        self._X, self._y, self.uses = X, y, {}

    def evaluate_once(self, name, model, threshold):
        if name in self.uses:
            raise RuntimeError(f"Test set already used for '{name}': it must not guide any further choice")
        self.uses[name] = 1
        return evaluate(model, self._X, self._y, threshold)


def evaluate(model, X_te, y_te, threshold):
    p = model.predict_proba(X_te)[:, 1]
    yhat = (p >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_te, yhat, labels=[0, 1]).ravel()
    return {"threshold": round(threshold, 4), "roc_auc": roc_auc_score(y_te, p),
            "pr_auc_average_precision": average_precision_score(y_te, p),
            "brier": brier_score_loss(y_te, p), "precision": precision_score(y_te, yhat, zero_division=0),
            "recall": recall_score(y_te, yhat), "f1": f1_score(y_te, yhat),
            "tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp),
            "accuracy": float((tn + tp) / len(y_te))}, p
# --8<-- end


# --8<-- G_interpretation
def label_shuffle_check(pipeline, grid, X_tr, y_tr, groups, real_pr_auc, outer=5, inner=3, n=5, seed=SEED):
    """Run the SAME nested procedure on labels shuffled at random (training rows only) and compare the
    pooled nested PR-AUC with the real one. Shuffles whole participants when groups exist, because a
    participant's label is the same on all of their rows. Real and shuffled scores are both nested, so
    neither carries tuning optimism and the comparison is like-for-like."""
    rng = np.random.default_rng(seed)
    shuffled = []
    for k in range(n):
        if groups is None:
            y_s = pd.Series(rng.permutation(y_tr.values), index=y_tr.index)
        else:
            lab = y_tr.groupby(groups).first()
            y_s = groups.map(pd.Series(rng.permutation(lab.values), index=lab.index)).astype(int)
        p_s, _, _ = nested_oof(pipeline, grid, X_tr, y_s, groups, outer, inner, seed + 17 * (k + 1))
        shuffled.append(average_precision_score(y_s, p_s))
    return {"real_nested_pr_auc": float(real_pr_auc), "shuffled_mean": float(np.mean(shuffled)),
            "share_shuffled_ge_real": float(np.mean(np.array(shuffled) >= real_pr_auc)), "n_shuffles": n}


def interpret(name, fitted, X_tr, y_tr, splits, seed=SEED):
    """Coefficients / impurity importance come from the fitted model alone. Permutation importance is
    measured on the VALIDATION folds of the training data; the test set is never touched here."""
    prep, model = fitted.named_steps["prep"], fitted.named_steps["model"]
    names = prep.get_feature_names_out()
    if name == "logistic_regression":      # inputs were standardised: per-1-SD effect on log-odds
        t = pd.DataFrame({"feature": names, "coef_per_1sd": model.coef_[0]})
        t["odds_ratio_per_1sd"] = np.exp(t.coef_per_1sd)
        return t.reindex(t.coef_per_1sd.abs().sort_values(ascending=False).index)
    t = pd.DataFrame({"feature": names, "impurity_importance": model.feature_importances_})
    drops = []
    for tr, va in splits:
        m = clone(fitted).fit(X_tr.iloc[tr], y_tr.iloc[tr])
        pi = permutation_importance(m, X_tr.iloc[va], y_tr.iloc[va], scoring="average_precision",
                                    n_repeats=5, random_state=seed, n_jobs=-1)
        drops.append(pd.Series(pi.importances_mean, index=X_tr.columns))
    perm = pd.concat(drops, axis=1).mean(axis=1)                  # on ORIGINAL columns
    return t.sort_values("impurity_importance", ascending=False), perm.sort_values(ascending=False)
# --8<-- end


